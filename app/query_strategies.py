"""
Step 13a - Query strategies: turn one question into the search queries used for retrieval.

    direct            [question]                                  no LLM call
    expansion         [question] + 3 rewrites in document words   1 call (fast model)
    decomposition     the sub-questions                           1 call (fast model)
    decompose+expand  each sub-question + its rewrites            1 + n calls (fast model)
"""
from pydantic import BaseModel, Field

from app.debug_logger import debug_config, get_logger, log_calls
from app.prompts import create_decomposition_prompt, create_expansion_prompt
from app.retriever import retrieve

log = get_logger(__name__)

DIRECT = "direct"
EXPANSION = "expansion"
DECOMPOSITION = "decomposition"
COMBINED = "decompose+expand"


class QueryList(BaseModel):
    """The list of queries the LLM returns (Pydantic: the LLM's output is checked and always a list)."""
    queries: list[str] = Field(description="Short search queries or sub-questions")


@log_calls
def create_expander(llm):
    """
    Build the query-expansion chain.

    Args:
        llm: A chat model (the cheaper fast model is enough).

    Returns:
        Runnable: .invoke({"question": ...}) returns a QueryList of rewrites.
    """
    log.info(f"expander chain created: expansion prompt -> {type(llm).__name__}.with_structured_output(QueryList)")
    return (create_expansion_prompt() | llm.with_structured_output(QueryList)).with_config(
        debug_config("expander (query expansion)"))


@log_calls
def create_decomposer(llm):
    """
    Build the query-decomposition chain.

    Args:
        llm: A chat model (the cheaper fast model is enough).

    Returns:
        Runnable: .invoke({"question": ...}) returns a QueryList of sub-questions.
    """
    log.info(f"decomposer chain created: decomposition prompt -> {type(llm).__name__}.with_structured_output(QueryList)")
    return (create_decomposition_prompt() | llm.with_structured_output(QueryList)).with_config(
        debug_config("decomposer (query decomposition)"))


def _log_queries(title, queries):
    log.info(f"{title}: {len(queries)} quer{'y' if len(queries) == 1 else 'ies'}")
    for i, query in enumerate(queries, start=1):
        log.info(f"    q{i}: {query!r}")


@log_calls
def build_queries(question, strategy, expander, decomposer):
    """
    Make the search queries for a strategy.

    Args:
        question (str): The customer's question.
        strategy (str): DIRECT, EXPANSION, DECOMPOSITION or COMBINED.
        expander: From create_expander().
        decomposer: From create_decomposer().

    Returns:
        list[str]: The queries to search with.
    """
    log.info(f"building queries with strategy {strategy!r}")

    if strategy == DIRECT:
        log.info("DIRECT: search with the question as it is (no LLM call)")
        queries = [question]
        _log_queries("DIRECT queries", queries)
        return queries

    if strategy == EXPANSION:
        log.info("EXPANSION: asking the fast LLM to rewrite the question in document words")
        rewrites = expander.invoke({"question": question}).queries
        _log_queries("EXPANSION rewrites generated by the LLM", rewrites)
        queries = [question] + rewrites
        _log_queries("EXPANSION final queries (original + rewrites)", queries)
        return queries

    log.info("DECOMPOSITION: asking the fast LLM to split the question into sub-questions")
    sub_questions = decomposer.invoke({"question": question}).queries
    _log_queries("DECOMPOSITION sub-questions generated by the LLM", sub_questions)
    if strategy == DECOMPOSITION:
        return sub_questions

    # COMBINED: every sub-question plus its rewrites
    log.info(f"DECOMPOSE+EXPAND: expanding each of the {len(sub_questions)} sub-question(s)")
    queries = []
    for number, sub in enumerate(sub_questions, start=1):
        rewrites = expander.invoke({"question": sub}).queries
        _log_queries(f"DECOMPOSE+EXPAND rewrites for sub-question {number} {sub!r}", rewrites)
        queries += [sub] + rewrites
    _log_queries("DECOMPOSE+EXPAND final queries", queries)
    return queries


@log_calls
def retrieve_for_queries(queries, vector_stores, region):
    """
    Search both bases with every query and remove duplicate chunks.

    Args:
        queries (list[str]): From build_queries().
        vector_stores (dict): {"knowledge": FAISS, "legal": FAISS}
        region (str): The customer's region.

    Returns:
        list[Document]: Unique chunks, in the order they were found.
    """
    found = {}
    total = 0
    for number, query in enumerate(queries, start=1):
        for name, store in vector_stores.items():
            log.info(f"query q{number} -> searching base {name!r}")
            documents = retrieve(query, store, region)
            total += len(documents)
            new = 0
            for doc in documents:
                if doc.page_content not in found:
                    new += 1
                found[doc.page_content] = doc  # same text = same chunk -> kept once
            log.info(f"query q{number} in {name!r}: {len(documents)} chunk(s), {new} new, "
                     f"{len(documents) - new} duplicate(s)")
    unique = list(found.values())
    log.info(f"retrieval for {len(queries)} quer(ies) × {len(vector_stores)} base(s): {total} chunk(s) found, "
             f"{len(unique)} unique after removing duplicates")
    for i, doc in enumerate(unique, start=1):
        log.info(f"  unique [{i}] {doc.metadata.get('title')!r} / section {doc.metadata.get('section', '')!r} "
                 f"({doc.metadata.get('region')})")
    return unique
